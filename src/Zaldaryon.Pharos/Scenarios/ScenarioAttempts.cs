using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Zaldaryon.Pharos.Scenarios;

/// <summary>Defines the retry attempt policy for flaky scenarios.</summary>
public readonly record struct ScenarioAttemptPolicy(int Attempts, int RequiredSuccesses)
{
    /// <summary>Reads the attempt policy from attributes on the method.</summary>
    public static ScenarioAttemptPolicy Read(MethodInfo method)
    {
        Attribute? attribute = method.GetCustomAttributes().FirstOrDefault(a =>
            a.GetType().GetProperty("Attempts")?.PropertyType == typeof(int) &&
            a.GetType().GetProperty("RequiredSuccesses")?.PropertyType == typeof(int));
        int attempts = (int?)attribute?.GetType().GetProperty("Attempts")?.GetValue(attribute) ?? 1;
        int required = (int?)attribute?.GetType().GetProperty("RequiredSuccesses")?.GetValue(attribute) ?? 1;
        if (attempts < 1 || required < 1 || required > attempts)
            throw new ArgumentOutOfRangeException(nameof(attempts), $"Scenario attempts must satisfy 1 <= RequiredSuccesses <= Attempts; got Attempts={attempts}, RequiredSuccesses={required}.");
        return new(attempts, required);
    }
}

/// <summary>Tracks execution state and artifacts across attempt retries.</summary>
public sealed class ScenarioAttemptState
{
    private static readonly AsyncLocal<ScenarioAttemptState?> s_current = new();
    private readonly List<string> _artifactDirectories = [];

    /// <summary>The active attempt state on this async flow.</summary>
    public static ScenarioAttemptState? Current { get => s_current.Value; set => s_current.Value = value; }

    /// <summary>Whether the scenario test method body was entered.</summary>
    public bool BodyEntered { get; set; }

    /// <summary>Whether the failure is eligible for retry.</summary>
    public bool RetryableBodyFailure { get; set; }

    /// <summary>The retryable failure exception.</summary>
    public Exception? RetryableFailure { get; set; }

    /// <summary>Whether the failure is non-retryable.</summary>
    public bool NonRetryableFailure { get; private set; }

    /// <summary>Whether the scenario requested a skip.</summary>
    public bool Skipped { get; set; }

    /// <summary>The current execution phase (e.g. setup, body, teardown, timeout, logged-errors).</summary>
    public string Phase { get; private set; } = "setup";

    /// <summary>All artifact directories captured during this attempt.</summary>
    public IReadOnlyList<string> ArtifactDirectories => _artifactDirectories;

    /// <summary>Marks this attempt as non-retryable.</summary>
    public void MarkNonRetryable(string phase = "setup")
    {
        NonRetryableFailure = true;
        Phase = phase;
    }

    /// <summary>Marks that the test body has started executing.</summary>
    public void EnterBody()
    {
        BodyEntered = true;
        Phase = "body";
    }

    /// <summary>Records an artifact directory generated by this attempt.</summary>
    public void AddArtifactDirectory(string directory) => _artifactDirectories.Add(directory);
}

/// <summary>An individual attempt's recorded outcome and metadata.</summary>
public sealed record ScenarioAttemptEntry(int Number, string Phase, string Outcome, double DurationSeconds, string? Failure, IReadOnlyList<string> ArtifactDirectories);

/// <summary>One per-test JSON manifest record of attempt history.</summary>
public sealed record ScenarioAttemptFragment(
    int SchemaVersion,
    string RunId,
    string Assembly,
    string FullyQualifiedName,
    string DisplayName,
    int Attempts,
    int RequiredSuccesses,
    string RawOutcome,
    string FinalOutcome,
    bool Flaky,
    IReadOnlyList<ScenarioAttemptEntry> AttemptHistory);

/// <summary>Writes attempt manifests to disk for worker coordination and flaky test analysis.</summary>
public static class ScenarioAttemptManifestWriter
{
    /// <summary>Environment variable designating the manifest directory.</summary>
    public const string DirectoryVariable = "PHAROS_ATTEMPT_MANIFEST_DIR";

    private static readonly JsonSerializerOptions s_json = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        WriteIndented = true,
    };

    /// <summary>Writes an attempt fragment to the designated manifest directory.</summary>
    public static void Write(
        string assembly,
        string fullyQualifiedName,
        string displayName,
        ScenarioAttemptPolicy policy,
        IReadOnlyList<ScenarioAttemptEntry> attempts,
        string outcome,
        bool flaky)
    {
        string? directory = Environment.GetEnvironmentVariable(DirectoryVariable);
        if (string.IsNullOrWhiteSpace(directory)) return;

        try
        {
            WriteCore(assembly, fullyQualifiedName, displayName, policy, attempts, outcome, flaky, directory);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Security.SecurityException or
                                   JsonException or ArgumentException or NotSupportedException)
        {
            System.Diagnostics.Trace.TraceWarning($"Could not write Pharos attempt metadata: {ex.GetType().Name}: {ex.Message}");
        }
    }

    private static void WriteCore(
        string assembly,
        string fullyQualifiedName,
        string displayName,
        ScenarioAttemptPolicy policy,
        IReadOnlyList<ScenarioAttemptEntry> attempts,
        string outcome,
        bool flaky,
        string directory)
    {
        Directory.CreateDirectory(directory);
        string identity = fullyQualifiedName + "\0" + displayName;
        string stem = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(identity)))[..16].ToLowerInvariant();
        ScenarioAttemptFragment record = new(1, Environment.GetEnvironmentVariable("PHAROS_RUN_ID") ?? "",
            assembly,
            fullyQualifiedName, displayName,
            policy.Attempts, policy.RequiredSuccesses, outcome, outcome, flaky, attempts);
        string path = Path.Combine(directory, $"{stem}-{Guid.NewGuid():N}.json");
        string temporary = path + ".tmp";
        try
        {
            File.WriteAllText(temporary, JsonSerializer.Serialize(record, s_json));
            File.Move(temporary, path);
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
    }
}
